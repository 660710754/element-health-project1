# =========================================================
# Empty Result
# =========================================================

def create_empty_result(
    question: str,
) -> dict[str, Any]:
    """
    สร้างผลลัพธ์เมื่อไม่พบข้อมูลที่เพียงพอ
    """

    return {
        "question": question,
        "answer": (
            "ไม่พบข้อมูลเพียงพอในฐานความรู้ของระบบ"
        ),
        "sources": [],
        "retrieved_chunks": [],
    }


# =========================================================
# Extract Sources
# =========================================================

def extract_sources(
    results: list[dict[str, Any]],
) -> list[str]:
    """
    ดึงรายชื่อไฟล์จากผล Retrieval
    และตัดชื่อไฟล์ที่ซ้ำกันออก
    """

    sources: list[str] = []

    for result in results:

        filename = result.get(
            "filename",
            "",
        )

        if (
            filename
            and filename not in sources
        ):
            sources.append(filename)

    return sources


# =========================================================
# Build RAG Prompt
# =========================================================

def build_rag_prompt(
    question: str,
    context: str,
) -> str:
    """
    รวมคำถามของผู้ใช้กับ Context
    ที่ค้นคืนจากระบบ IR
    """

    return f"""
คำถามของผู้ใช้:
{question}

==================================================
CONTEXT จากฐานความรู้
==================================================

{context}

==================================================
คำสั่งในการตอบ
==================================================

ตอบคำถามของผู้ใช้โดยอ้างอิงเฉพาะข้อมูล
ที่ปรากฏใน CONTEXT ด้านบนเท่านั้น

ระบบนี้เน้นธาตุเจ้าเรือนปัจจุบันเป็นหลัก

หากคำถามเกี่ยวกับลักษณะของธาตุ
ให้อธิบายจากลักษณะร่างกาย บุคลิก พฤติกรรม
หรือลักษณะและอาการปัจจุบันที่อยู่ใน CONTEXT

หากคำถามเกี่ยวกับอาหาร
ให้ใช้เฉพาะรายการอาหารหรือข้อมูลอาหาร
ที่อยู่ใน CONTEXT

ห้ามเพิ่มข้อมูลที่ไม่มีใน CONTEXT

หากข้อมูลไม่เพียงพอ ให้ตอบว่า:
"ไม่พบข้อมูลเพียงพอในฐานความรู้ของระบบ"
"""


# =========================================================
# RAG System
# =========================================================

class RAGSystem:
    """
    ระบบ Retrieval-Augmented Generation

    Workflow:

    คำถามผู้ใช้
        ↓
    TfidfRetriever
        ↓
    Top-k Chunks
        ↓
    build_context()
        ↓
    Ollama
        ↓
    คำตอบภาษาไทย
    """

    def __init__(
        self,
        model: str = DEFAULT_MODEL,
        top_k: int = DEFAULT_TOP_K,
    ) -> None:

        if top_k <= 0:
            raise ValueError(
                "top_k ต้องมากกว่า 0"
            )

        self.model = model
        self.top_k = top_k

        # ใช้ระบบ IR ที่เราทำไว้แล้ว
        self.retriever = TfidfRetriever()


    # -----------------------------------------------------
    # Retrieval
    # -----------------------------------------------------

    def retrieve(
        self,
        question: str,
    ) -> list[dict[str, Any]]:
        """
        ค้นข้อมูลจาก knowledge/
        """

        return self.retriever.search(
            query=question,
            top_k=self.top_k,
        )


    # -----------------------------------------------------
    # Generation
    # -----------------------------------------------------

    def answer(
        self,
        question: str,
    ) -> dict[str, Any]:
        """
        ทำ RAG ตั้งแต่ Retrieval
        จนถึง Generation
        """

        question = question.strip()

        # ---------------------------------------------
        # ตรวจคำถามว่าง
        # ---------------------------------------------

        if not question:

            return {
                "question": "",
                "answer": (
                    "กรุณาระบุคำถามก่อนใช้งานระบบ"
                ),
                "sources": [],
                "retrieved_chunks": [],
            }

        # ---------------------------------------------
        # 1. Retrieval
        # ---------------------------------------------

        results = self.retrieve(
            question
        )

        if not results:

            return create_empty_result(
                question
            )

        # ---------------------------------------------
        # 2. Build Context
        # ---------------------------------------------

        context = build_context(
            results
        )

        if not context.strip():

            return create_empty_result(
                question
            )

        # ---------------------------------------------
        # 3. Build Prompt
        # ---------------------------------------------

        user_prompt = build_rag_prompt(
            question=question,
            context=context,
        )

        # ---------------------------------------------
        # 4. Generation ด้วย Ollama
        # ---------------------------------------------

        try:

            response = ollama.chat(
                model=self.model,
                messages=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT,
                    },
                    {
                        "role": "user",
                        "content": user_prompt,
                    },
                ],
                options={
                    # ลดความสุ่มเพื่อให้คำตอบ
                    # ยึดตามเอกสารมากขึ้น
                    "temperature": 0.2,
                },
            )

        except Exception as error:

            return {
                "question": question,
                "answer": (
                    "ไม่สามารถเชื่อมต่อกับ Ollama ได้\n\n"
                    f"รายละเอียด: {error}"
                ),
                "sources": [],
                "retrieved_chunks": results,
            }

        # ---------------------------------------------
        # 5. อ่านคำตอบ
        # ---------------------------------------------

        answer_text = (
            response["message"]["content"]
            .strip()
        )

        if not answer_text:

            answer_text = (
                "ไม่พบข้อมูลเพียงพอ"
                "ในฐานความรู้ของระบบ"
            )

        # ---------------------------------------------
        # 6. Sources
        # ---------------------------------------------

        sources = extract_sources(
            results
        )

        # ---------------------------------------------
        # 7. Return
        # ---------------------------------------------

        return {
            "question": question,
            "answer": answer_text,
            "sources": sources,
            "retrieved_chunks": results,
        }


# =========================================================
# Terminal Output
# =========================================================

def print_rag_result(
    result: dict[str, Any],
) -> None:
    """
    แสดงผล RAG ใน Terminal
    """

    print()
    print("=" * 70)

    print(
        "คำถาม:",
        result["question"],
    )

    print("=" * 70)

    print()
    print("คำตอบ")
    print("-" * 70)

    print(
        result["answer"]
    )

    print()
    print("แหล่งข้อมูลที่ระบบค้นคืน")
    print("-" * 70)

    sources = result.get(
        "sources",
        [],
    )

    if not sources:

        print(
            "ไม่พบแหล่งข้อมูล"
        )

    else:

        for source in sources:

            print(
                f"- {source}"
            )

    print()

    retrieved_chunks = result.get(
        "retrieved_chunks",
        [],
    )

    if retrieved_chunks:

        print(
            "จำนวนข้อมูลที่ค้นคืน:",
            len(retrieved_chunks),
        )

    print("=" * 70)


